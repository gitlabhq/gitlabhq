# frozen_string_literal: true

require 'spec_helper'

RSpec.describe Gitlab::Database::QueryLogComment, feature_category: :database do
  describe '.tag_sql' do
    let(:connection) { ApplicationRecord.connection }

    def extract(query, tag)
      connection.select_value("SELECT #{described_class.tag_sql(connection.quote(query), tag)}")
    end

    using RSpec::Parameterized::TableSyntax

    # rubocop:disable Layout/LineLength -- the queries are easier to compare on one line
    where(:query, :application, :endpoint_id, :db_config_database) do
      # Rails 7.2 keeps the order configured in Gitlab::QueryLogs.tags
      '/*application:web,correlation_id:01ABC,endpoint_id:Projects::IssuesController#show,db_config_database:gitlabhq_production,db_config_name:main*/ SELECT 1' | 'web' | 'Projects::IssuesController#show' | 'gitlabhq_production'
      # Rails 8 sorts tags by name
      '/*application:sidekiq,correlation_id:01ABC,db_config_database:gitlabhq_production,db_config_name:main,endpoint_id:UsageEvents::DumpWriteBufferCronWorker,feature_category:database,jid:14a81001232a16804a884482*/ SELECT 1' | 'sidekiq' | 'UsageEvents::DumpWriteBufferCronWorker' | 'gitlabhq_production'
      '/*console_hostname:host,console_username:user,correlation_id:01ABC,db_config_database:gitlabhq_production,endpoint_id:POST /api/:version/jobs/request*/ SELECT 1' | nil | 'POST /api/:version/jobs/request' | 'gitlabhq_production'
      "  \n/*application:web*/ SELECT 1" | 'web' | nil | nil
      'SELECT 1 /*application:web,endpoint_id:Foo::Bar*/' | nil | nil | nil
      "/*application:web*/ SELECT '/*,endpoint_id:Foo::Bar,db_config_database:other*/'" | 'web' | nil | nil
      '/*application:web*/ /*endpoint_id:Foo::Bar*/ SELECT 1' | 'web' | nil | nil
      'SELECT 1' | nil | nil | nil
    end
    # rubocop:enable Layout/LineLength

    with_them do
      it 'extracts tags from the leading comment only', :aggregate_failures do
        expect(extract(query, :application)).to eq(application)
        expect(extract(query, :endpoint_id)).to eq(endpoint_id)
        expect(extract(query, :db_config_database)).to eq(db_config_database)
      end
    end

    it 'returns NULL for a NULL query' do
      expect(connection.select_value("SELECT #{described_class.tag_sql('NULL::text', :application)}")).to be_nil
    end

    it 'raises for an unknown tag' do
      expect { described_class.tag_sql('query', :jid) }.to raise_error(KeyError)
    end

    context 'with a comment generated by ActiveRecord::QueryLogs' do
      before do
        # Production prepends the comment; test appends it.
        allow(ActiveRecord::QueryLogs).to receive(:prepend_comment).and_return(true)
      end

      let(:query) do
        Gitlab::ApplicationContext.with_context(caller_id: 'Projects::IssuesController#show') do
          ActiveRecord::QueryLogs.call('SELECT 1', connection)
        end
      end

      it 'extracts the tags in the order the running Rails version writes them', :aggregate_failures do
        expect(query).to start_with('/*')
        expect(extract(query, :application)).to eq(Gitlab.process_name)
        expect(extract(query, :endpoint_id)).to eq('Projects::IssuesController#show')
        expect(extract(query, :db_config_database)).to eq(Gitlab::Database.db_config_database(connection))
      end
    end
  end
end
