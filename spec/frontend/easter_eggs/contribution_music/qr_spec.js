const render = (grid) => grid.map((row) => row.map((dark) => (dark ? '#' : '.')).join(''));

describe('encodeQr', () => {
  it('matches a reference encoding of a profile URL', () => {
    expect(render(encodeQr('https://gitlab.com/clavimoniere'))).toEqual(PROFILE_QR);
  });

  it('fits up to 58 bytes', () => {
    expect(encodeQr('a'.repeat(58))).toHaveLength(41);
    expect(encodeQr('a'.repeat(59))).toBeNull();
  });

  it('measures capacity in UTF-8 bytes', () => {
    expect(encodeQr('é'.repeat(29))).toHaveLength(41);
    expect(encodeQr('é'.repeat(30))).toBeNull();
  });
});
